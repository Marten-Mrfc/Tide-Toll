# python3 assets/src/2d/icons-n3.py [name-prefix ...]  ->  assets/icons/{shop,boon,perk,milestone,ach,msg,nav}-*.svg and the old names the interface asks for today (iconkit/msg.py ALIASES, ui-coin/lock/check)
# Night 3, track IC: one icon for every purchase, boon, perk, milestone, achievement, kind of message and navigation
# button, in one drawing vocabulary (assets/src/2d/iconkit/draw.py; docs/plans/n3/style-sheet.md section 8): a 48 x 48
# file shown at 24, one Ink line 3 wide with round ends, one flat palette colour, no letters or digits.
# Also writes their rows in assets/LEDGER.csv (self-made). Contact sheets: tools/asset-audit/icon_sheets.py.
import sys
sys.dont_write_bytecode = True  # never leave compiled Python files in the repository
import csv, datetime, io, pathlib

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(HERE))
from iconkit import shop, ach, msg  # noqa: E402

GROUPS = [("Shop", shop.shop), ("Boons", shop.boons), ("Perks and milestones", shop.perks),
          ("Achievements", ach.achievements), ("Messages", msg.messages), ("Navigation", msg.nav), ("Today's names", msg.today)]

USED = {
    "shop": "Shop row icon (TownHud.ShopIconName)", "boon": "Choice of two: boon icon", "perk": "Perk note icon",
    "milestone": "Milestone note icon", "ach": "Achievements page and note: medal", "msg": "Message icon by kind",
    "nav": "Navigation button / tide dial icon",
    "ui": "Interface icon under the name TownHud asks for today", "up": "Boon icon under the name TownHud.BoonIcon asks for today",
    "good": "Boon icon under the name TownHud.BoonIcon asks for today",
}


def all_icons():
    out = []
    for gname, fn in GROUPS:
        for ic in fn():
            out.append((gname, ic))
    return out


def ledger_rows(icons):
    path = ROOT / "assets" / "LEDGER.csv"
    text = path.read_text()
    rows = list(csv.reader(io.StringIO(text)))
    head, body = rows[0], rows[1:]
    keep = {r[0]: r for r in body}
    today = datetime.date.today().isoformat()
    for _, ic in icons:
        item = f"assets/icons/{ic.name}.svg"
        src = ("generated by assets/src/2d/icons-n3.py; script written by Claude Opus 5.5; SVG written as code: "
               "48 x 48, Ink line 3 with round ends, one flat palette colour")
        used = f"{USED[ic.name.split('-')[0]]}: {ic.note}"
        old = keep.get(item)
        keep[item] = [item, "icon", src, "self-made", "", used, old[6] if old and old[2] == src and old[5] == used else today, "yes"]
    order = [r[0] for r in body] + [f"assets/icons/{ic.name}.svg" for _, ic in icons if f"assets/icons/{ic.name}.svg" not in {r[0] for r in body}]
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(head)
    for k in order:
        w.writerow(keep[k])
    path.write_text(buf.getvalue())


def main():
    want = sys.argv[1:]
    icons = all_icons()
    names = [ic.name for _, ic in icons]
    assert len(names) == len(set(names)), "two icons share a name"
    outdir = ROOT / "assets" / "icons"
    n = 0
    for _, ic in icons:
        if want and not any(ic.name.startswith(w) for w in want):
            continue
        (outdir / f"{ic.name}.svg").write_text(ic.svg())
        n += 1
    ledger_rows(icons)
    print(f"icons-n3: {n} icons written, {len(icons)} ledger rows")


if __name__ == "__main__":
    main()
