# python3 assets/src/2d/icons-trades2.py  ->  assets/icons/trade-{wool,cloth,boat}.svg
# n7 step 3 (the second age's trades, docs/plans/n7/trades2-build-sheet.md): three icons in the family of
# icons-trades.py (48 x 48 shown at 24 or 19, one Ink line 3 wide with round ends, one flat palette colour plus Paper,
# no letters). Each is its trade's headwear on a head seen from the front, three-quarter, as on the figure:
#   trade-wool:  the shepherd: a Slate roof felt hat, the brim narrower than the reaper's straw hat (round 3)
#   trade-cloth: the weaver: a Meadow stocking cap, its tail falling to one side, a Paper tassel
#   trade-boat:  the porter: a Deep water fantail hood, the flap falling behind to the shoulder (round 3)
import sys
sys.dont_write_bytecode = True
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent))
from iconkit.draw import Icon, path, circle, dot  # noqa: E402
from common import ledger  # noqa: E402

ROOT = HERE.parents[2]


def shoulders(f="c"):
    return path("M9 46 V42 Q9 33 24 33 Q39 33 39 42 V46", f)


def icons():
    return [
        Icon("trade-wool", "slate", "the shepherd: a grey felt hat, its brim narrower than the reaper's").add(
            shoulders("packed"),
            circle(24, 29, 9, "p"), dot(28, 31, 1.3),
            path("M16.5 21 Q16 11 24 11 Q32 11 31.5 21Z", "c"),                       # round crown
            path("M8 22.5 Q8 19 24 19 Q40 19 40 22.5 Q40 25.5 24 25.5 Q8 25.5 8 22.5Z", "c")),   # brim, 32 across (the reaper's 42)
        Icon("trade-cloth", "meadow", "the weaver: a green stocking cap, its tail to one side, a tassel").add(
            shoulders("packed"),
            circle(22, 28, 9.5, "p"), dot(26, 30, 1.3),
            path("M11.5 26 Q11 12 24 11 Q36 11 34 22 L39 33 L33 30 Q30 23 24 23 Q16 23 11.5 26Z", "c"),
            circle(40, 36, 3.5, "p")),                                                   # tassel
        Icon("trade-boat", "slate", "the porter: a dark blue fantail hood, the flap behind").add(
            shoulders("packed"),
            path("M10 37 L8 24 Q9 12 22 12 Q33 12 34 21 L26 24 Q19 26 17 37Z", "c"),     # crown and the flap behind
            circle(27, 28, 8.5, "p"), dot(30.5, 29.5, 1.3),
            path("M24 21 H39 Q40 24 36 24 H24Z", "c")),                                  # the short peak
    ]


DEEP = "#3F5F75"   # Deep water (palette.json; not in iconkit's short list)


def main():
    outdir = ROOT / "assets" / "icons"
    for ic in icons():
        if ic.name == "trade-boat":
            ic.c = DEEP
        p = outdir / f"{ic.name}.svg"
        p.write_text(ic.svg().replace("generated by assets/src/2d/icons-n3.py", "generated by assets/src/2d/icons-trades2.py"))
        ledger.add("icons", p, kind="icon", generator=__file__,
                   used_in=f"Trades of the second age (n7 step 3, board docs/plans/n7/mockup/hats-trades2.png): {ic.note}",
                   verified=True, note="SVG written as code: 48 x 48, Ink line 3 with round ends, one flat palette colour")
    print("icons-trades2: 3 icons written")


if __name__ == "__main__":
    main()
