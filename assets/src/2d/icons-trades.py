# python3 assets/src/2d/icons-trades.py  ->  assets/icons/trade-{water,grain,flour,hand}.svg, shop-train.svg
# n7 step 2 (the trades, docs/plans/n7/trades-design.md): the trades' icons in the shop's family (iconkit/draw.py: a
# 48 x 48 file shown at 20 or 24, one Ink line 3 wide with round ends, one flat palette colour plus Paper, no letters
# or digits). Each trade is its headwear, as on the figure: a head seen from the front, three-quarter, wearing it.
#   trade-water: a blue kerchief (River) tied over the head, knot and tail at the back
#   trade-grain: a wide straw hat (Thatch), the brim wider than the head
#   trade-flour: a white flat cap (Limewash) with a short peak
#   trade-hand:  a bare head with hair (Packed earth): takes whatever pays best
#   shop-train:  a sickle's blade drawn over a whetstone (Slate), two sparks: the Train row
# Rows in the ledger through common.ledger (fragments with ASSET_LEDGER_FRAGMENTS=1, as the models do).
import sys
sys.dont_write_bytecode = True
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent))
from iconkit.draw import Icon, path, circle, ellipse, line, dot  # noqa: E402
from common import ledger  # noqa: E402

ROOT = HERE.parents[2]


def shoulders(f="c"):
    return path("M9 46 V42 Q9 33 24 33 Q39 33 39 42 V46", f)


def face(cy=27, f="p"):
    return [circle(24, cy, 9, f), dot(27.5, cy + 1, 1.3)]


def icons():
    out = []
    out.append(Icon("trade-water", "river", "the water carrier: a blue kerchief").add(
        shoulders(),
        circle(24, 26, 10, "p"), dot(28, 28, 1.3),
        path("M13.5 25 Q14 13 24 13 Q35 13 34.5 25 Q24 20 13.5 25Z", "c"),          # the cloth over the crown
        path("M14 24 L8 30 L12 31 L15 27", "c")))                                    # knot and tail at the back
    out.append(Icon("trade-grain", "wheat", "the reaper: a wide straw hat").add(
        shoulders(),
        circle(24, 29, 9, "p"), dot(28, 31, 1.3),
        path("M17 21 Q18 9 24 9 Q30 9 31 21Z", "c"),                                  # crown
        ellipse(24, 21.5, 21, 5, "c"),                                                # brim, wider than the head
        line((17.5, 20), (30.5, 20))))
    out.append(Icon("trade-flour", "lime", "the miller: a white flat cap").add(
        shoulders(),
        circle(24, 28, 9.5, "p"), dot(28, 30, 1.3),
        path("M13.5 25 Q13 15 24 14.5 Q36 14.5 36 22 L35 25 Z", "c"),                 # the cap's round top
        path("M30 24 Q37 23 41 26 Q36 28 30 27Z", "c")))                              # the peak
    out.append(Icon("trade-hand", "packed", "the Hand: a bare head, whatever pays best").add(
        shoulders(),
        circle(24, 26, 10, "p"), dot(28, 28, 1.3),
        path("M14 25 Q13 15 24 15 Q34 15 34 22 Q28 19 22 21 Q17 22 14 25Z", "c")))   # hair
    out.append(Icon("shop-train", "slate", "Train a trade: a blade over a whetstone, two sparks").add(
        path("M6 40 Q6 33 14 33 H38 Q44 33 44 40 Z", "c"),                            # the whetstone
        path("M10 30 Q22 14 40 12 Q30 20 18 30 Z", "p"),                              # a sickle's blade being honed
        line((40, 22), (44, 19)), line((38, 27), (44, 27))))                          # sparks
    return out


def main():
    outdir = ROOT / "assets" / "icons"
    for ic in icons():
        p = outdir / f"{ic.name}.svg"
        p.write_text(ic.svg().replace("generated by assets/src/2d/icons-n3.py", "generated by assets/src/2d/icons-trades.py"))
        ledger.add("icons", p, kind="icon", generator=__file__,
                   used_in=f"Trades (n7 step 2, mock-up board docs/plans/n7/mockup): {ic.note}", verified=True,
                   note="SVG written as code: 48 x 48, Ink line 3 with round ends, one flat palette colour")
    print(f"icons-trades: {len(icons())} icons written")


if __name__ == "__main__":
    main()
