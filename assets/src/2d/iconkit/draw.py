# The night-3 icon vocabulary (docs/plans/n3/style-sheet.md section 8): a 48 x 48 file shown at 24, one Ink line 3 wide
# with round ends and joins, one flat palette colour per icon (plus Paper inside shapes), no letters or digits.
# Every glyph is drawn on the full 48 box; `group` scales one into a smaller place and keeps the line at 3.
import math

SW = 3.0
INK = "#2B2620"
COL = {  # palette (assets/src/common/palette.json)
    "paper": "#F2EAD8", "meadow": "#7FA35B", "bent": "#A9B86E", "earth": "#B89568", "packed": "#8C6A48",
    "river": "#5B7F95", "wheat": "#C9A55A", "brick": "#A4553A", "slate": "#5E6B78", "green": "#44604F",
    "stone": "#A9A69C", "lime": "#E9E2CF", "mud": "#5E4A36",
}


def _fill(f, ctx):
    if f is None:
        return "none"
    if f == "c":
        return ctx["c"]
    if f == "p":
        return COL["paper"]
    if f == "i":
        return INK
    return COL.get(f, f)


class Icon:
    def __init__(self, name, colour, note=""):
        self.name, self.c, self.note, self.parts = name, COL[colour], note, []

    def add(self, *items):
        for it in items:
            if isinstance(it, (list, tuple)):
                self.add(*it)
            else:
                self.parts.append(it)
        return self

    def svg(self):
        ctx = {"c": self.c}
        body = "\n".join("  " + p(ctx, SW) for p in self.parts)
        return (f'<svg xmlns="http://www.w3.org/2000/svg" width="48" height="48" viewBox="0 0 48 48" fill="none">\n'
                f'  <!-- Tide & Toll icon "{self.name}"; generated by assets/src/2d/icons-n3.py{(": " + self.note) if self.note else ""} -->\n'
                f'  <g stroke="{INK}" stroke-width="{SW:g}" stroke-linecap="round" stroke-linejoin="round">\n'
                f'{body}\n  </g>\n</svg>\n')


def _n(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def path(d, f=None):
    return lambda ctx, sw: f'<path d="{d}" fill="{_fill(f, ctx)}"/>'


def circle(cx, cy, r, f=None):
    return lambda ctx, sw: f'<circle cx="{_n(cx)}" cy="{_n(cy)}" r="{_n(r)}" fill="{_fill(f, ctx)}"/>'


def ellipse(cx, cy, rx, ry, f=None, rot=0):
    t = f' transform="rotate({_n(rot)} {_n(cx)} {_n(cy)})"' if rot else ""
    return lambda ctx, sw: f'<ellipse cx="{_n(cx)}" cy="{_n(cy)}" rx="{_n(rx)}" ry="{_n(ry)}" fill="{_fill(f, ctx)}"{t}/>'


def rect(x, y, w, h, f=None, r=1.5):
    return lambda ctx, sw: f'<rect x="{_n(x)}" y="{_n(y)}" width="{_n(w)}" height="{_n(h)}" rx="{_n(r)}" fill="{_fill(f, ctx)}"/>'


def poly(pts, f=None):
    d = "M" + " L".join(f"{_n(x)} {_n(y)}" for x, y in pts) + "Z"
    return path(d, f)


def line(*pts):
    d = "M" + " L".join(f"{_n(x)} {_n(y)}" for x, y in pts)
    return path(d, None)


def dot(cx, cy, r=1.6):
    """A small solid Ink point (stroke-free look: Ink on Ink)."""
    return lambda ctx, sw: f'<circle cx="{_n(cx)}" cy="{_n(cy)}" r="{_n(r)}" fill="{INK}" stroke="none"/>'


def group(parts, tx=0.0, ty=0.0, s=1.0):
    """Parts drawn on the 48 box, placed at (tx, ty) and scaled by s; the line stays 3 on the final icon."""
    def out(ctx, sw):
        inner = " ".join(p(ctx, sw / s) for p in _flat(parts))
        return f'<g transform="translate({_n(tx)} {_n(ty)}) scale({s:g})" stroke-width="{sw / s:.3g}">{inner}</g>'
    return out


def _flat(parts):
    for p in parts:
        if isinstance(p, (list, tuple)):
            yield from _flat(p)
        else:
            yield p


def star_pts(cx, cy, R, r, n=5, rot=-90):
    pts = []
    for i in range(n * 2):
        a = math.radians(rot + i * 180 / n)
        rr = R if i % 2 == 0 else r
        pts.append((cx + rr * math.cos(a), cy + rr * math.sin(a)))
    return pts


def place(parts, box=(0, 0, 48), at=(24, 24), size=48):
    """Scale a full-box glyph to `size` with its centre at `at`."""
    s = size / 48.0
    return group(parts, at[0] - 24 * s, at[1] - 24 * s, s)
